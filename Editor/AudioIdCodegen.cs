using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Astra.Echo.Editor
{
    /// <summary>
    /// Generates a consumer-side static registry, <c>public static partial class AudioIds</c>,
    /// exposing one <c>public static readonly AudioId Xxx</c> per <see cref="AudioDefinition"/>.
    /// Members are named after the definition's PascalCase identifier and carry the
    /// stable asset GUID, so renames are safe (the value never changes).
    ///
    /// <para>Output: <c>&lt;AudioImportSettings.GeneratedOutputFolder&gt;/AudioIds.Generated.cs</c>.
    /// The registry lives in the consumer project (never inside the read-only package), in the
    /// assembly that owns the folder.</para>
    ///
    /// <para>The codegen avoids unnecessary writes — if the file already matches the
    /// expected output, nothing is touched (no AssetDatabase ping).</para>
    /// </summary>
    [UnityEngine.Scripting.APIUpdating.MovedFrom(false, "Core.Audio.Editor", "Core.Audio.Editor", "AudioIdCodegen")]
    public static class AudioIdCodegen
    {
        public const string OutputFileName = "AudioIds.Generated.cs";

        /// <summary>One generated registry member.</summary>
        internal readonly struct Entry
        {
            public readonly string MemberName;
            public readonly string Guid;
            public readonly string SourceLabel;

            public Entry(string memberName, string guid, string sourceLabel)
            {
                MemberName = memberName;
                Guid = guid;
                SourceLabel = sourceLabel;
            }
        }

        public static void Generate(IReadOnlyList<AudioDefinition> definitions)
        {
            List<Entry> entries = new List<Entry>(definitions.Count);
            for (int i = 0; i < definitions.Count; i++)
            {
                AudioDefinition def = definitions[i];
                if (def == null) continue;

                string assetPath = AssetDatabase.GetAssetPath(def);
                string guid = AssetDatabase.AssetPathToGUID(assetPath);
                if (string.IsNullOrEmpty(guid)) continue;

                entries.Add(new Entry(def.Label, guid, def.name));
            }

            string content = BuildContent(BuildEntries(entries));
            string outputFolder = ResolveOutputFolder(AudioDatabaseRegistry.FindImportSettings());
            string targetPath = outputFolder + "/" + OutputFileName;

            EnsureFolder(outputFolder);

            if (!WriteIfChanged(targetPath, content))
                return;

            AssetDatabase.ImportAsset(targetPath, ImportAssetOptions.ForceUpdate);
            Debug.Log($"[Echo] Regenerated AudioIds registry ({entries.Count} entries) → {targetPath}");
        }

        [MenuItem("Tools/Astra/Echo/Regenerate Audio ID Registry")]
        public static void RegenerateMenu()
        {
            List<AudioDefinition> defs = AudioDatabaseRegistry.FindAllDefinitions();
            Generate(defs);
        }

        /// <summary>
        /// Sanitises the raw labels into unique member names (duplicates get <c>_2</c>, <c>_3</c>…)
        /// and sorts by member name for stable diffs. <see cref="Entry.MemberName"/> of the inputs
        /// holds the raw label.
        /// </summary>
        internal static List<Entry> BuildEntries(IReadOnlyList<Entry> rawEntries)
        {
            List<Entry> entries = new List<Entry>(rawEntries.Count);
            Dictionary<string, int> nameCounts = new Dictionary<string, int>();

            for (int i = 0; i < rawEntries.Count; i++)
            {
                Entry raw = rawEntries[i];
                string baseName = AudioMemberNameSanitizer.ToPascalCaseIdentifier(raw.MemberName);
                string memberName = baseName;

                if (nameCounts.TryGetValue(baseName, out int n))
                {
                    n++;
                    nameCounts[baseName] = n;
                    memberName = baseName + "_" + n;
                }
                else
                {
                    nameCounts[baseName] = 1;
                }

                entries.Add(new Entry(memberName, raw.Guid, raw.SourceLabel));
            }

            entries.Sort((Entry a, Entry b) => string.CompareOrdinal(a.MemberName, b.MemberName));
            return entries;
        }

        internal static string BuildContent(IReadOnlyList<Entry> entries)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by Astra.Echo.Editor.AudioIdCodegen.");
            sb.AppendLine("// DO NOT edit by hand — your changes will be overwritten.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("using Astra.Echo;");
            sb.AppendLine();
            sb.AppendLine("public static partial class AudioIds");
            sb.AppendLine("{");

            for (int i = 0; i < entries.Count; i++)
            {
                Entry e = entries[i];
                sb.AppendLine($"    /// <summary>Source asset: {Escape(e.SourceLabel)}</summary>");
                sb.AppendLine($"    public static readonly AudioId {e.MemberName} = new AudioId(\"{e.Guid}\");");
            }

            sb.AppendLine("}");
            return sb.ToString();
        }

        /// <summary>Writes <paramref name="content"/> only when it differs from the file on disk.</summary>
        /// <returns>True when the file was written.</returns>
        internal static bool WriteIfChanged(string targetPath, string content)
        {
            string existing = File.Exists(targetPath) ? File.ReadAllText(targetPath) : null;
            if (string.Equals(existing, content, StringComparison.Ordinal))
                return false;

            File.WriteAllText(targetPath, content);
            return true;
        }

        private static string Escape(string s) => s == null ? "" : s.Replace("\"", "\\\"").Replace("<", "&lt;").Replace(">", "&gt;");

        /// <summary>
        /// Folder (relative to the project root, forward slashes) the registry is written to:
        /// <see cref="AudioImportSettings.GeneratedOutputFolder"/>, or its default when no
        /// settings asset exists or the field is empty.
        /// </summary>
        public static string ResolveOutputFolder(AudioImportSettings settings)
        {
            string folder = settings != null ? settings.GeneratedOutputFolder : null;
            if (string.IsNullOrWhiteSpace(folder)) folder = AudioImportSettings.DefaultGeneratedOutputFolder;
            return folder.Replace('\\', '/').TrimEnd('/');
        }

        private static void EnsureFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder)) return;

            string[] parts = folder.Split('/');
            string current = parts[0];
            for (int i = 1; i < parts.Length; i++)
            {
                string next = current + "/" + parts[i];
                if (!AssetDatabase.IsValidFolder(next))
                    AssetDatabase.CreateFolder(current, parts[i]);
                current = next;
            }
        }
    }
}
