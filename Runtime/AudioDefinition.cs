using System.Collections.Generic;
using UnityEngine;
using UnityEngine.Audio;

namespace Astra.Echo
{
    /// <summary>
    /// ScriptableObject describing a single playable sound: clip, type, default playback parameters,
    /// optional 3D spatial settings, and authorable modulators.
    ///
    /// <para>The <see cref="Id"/> is auto-assigned by the editor pipeline (see AudioPostprocessor)
    /// based on the asset GUID, and consumed by the codegen to expose stable members through
    /// the generated <c>AudioId</c> registry.</para>
    /// </summary>
    [CreateAssetMenu(fileName = "AudioDefinition", menuName = "Astra/Echo/Audio Definition")]
    [UnityEngine.Scripting.APIUpdating.MovedFrom(false, "Core.Audio", "Core.Audio", "AudioDefinition")]
    public sealed class AudioDefinition : ScriptableObject
    {
        [Header("Identity")]
        [Tooltip("Auto-generated by the editor pipeline. Stable across renames (GUID-based).")]
        [SerializeField] private AudioId _id;

        [Tooltip("Optional human-readable label. Defaults to the asset name when empty.")]
        [SerializeField] private string _label;

        [SerializeField] private AudioType _type = AudioType.Sfx;

        [Header("Clip")]
        [SerializeField] private AudioClip _clip;

        [Header("Defaults")]
        [Range(0f, 1f)] [SerializeField] private float _baseVolume = 1f;
        [Range(0.1f, 3f)] [SerializeField] private float _basePitch = 1f;
        [SerializeField] private bool _baseLoop;

        [Header("Routing (optional)")]
        [Tooltip("Optional override mixer group. When null, the AudioService routes via type.")]
        [SerializeField] private AudioMixerGroup _mixerGroupOverride;

        [Header("Spatial (optional, for 3D content)")]
        [Range(0f, 1f)] [Tooltip("0 = pure 2D, 1 = pure 3D.")]
        [SerializeField] private float _spatialBlend;
        [SerializeField] private AudioRolloffMode _rolloff = AudioRolloffMode.Logarithmic;
        [Min(0f)] [SerializeField] private float _minDistance = 1f;
        [Min(0f)] [SerializeField] private float _maxDistance = 500f;

        [Header("Modulators")]
        [Tooltip("Modulators applied at playback time. Use [SerializeReference]-friendly classes.")]
        [SerializeReference] private List<SoundModulatorBase> _modulators = new List<SoundModulatorBase>();

        [Header("Options")]
        [Tooltip("Static playback options applied right before the source is started. " +
                 "Use [SerializeReference]-friendly classes.")]
        [SerializeReference] private List<SoundOptionBase> _options = new List<SoundOptionBase>();

        public AudioId Id => _id;
        public string Label => string.IsNullOrEmpty(_label) ? name : _label;
        public AudioType Type => _type;
        public AudioClip Clip => _clip;

        public float BaseVolume => _baseVolume;
        public float BasePitch => _basePitch;
        public bool BaseLoop => _baseLoop;

        public AudioMixerGroup MixerGroupOverride => _mixerGroupOverride;

        public float SpatialBlend => _spatialBlend;
        public AudioRolloffMode Rolloff => _rolloff;
        public float MinDistance => _minDistance;
        public float MaxDistance => _maxDistance;

        public IReadOnlyList<SoundModulatorBase> Modulators => _modulators;
        public IReadOnlyList<SoundOptionBase> Options => _options;

        /// <summary>
        /// Editor-only: sets the id. Runtime code must not call this.
        /// Kept public so the editor pipeline (which lives in a separate assembly)
        /// can persist a stable id without reflection or friend-assembly wiring.
        /// </summary>
        public void EditorSetId(AudioId id)
        {
            _id = id;
        }

        /// <summary>
        /// Editor-only: sets the type. Used by AudioPostprocessor when classifying clips.
        /// </summary>
        public void EditorSetType(AudioType type)
        {
            _type = type;
        }

        /// <summary>
        /// Editor-only: assigns the clip when auto-creating from an imported asset.
        /// </summary>
        public void EditorSetClip(AudioClip clip)
        {
            _clip = clip;
        }
    }
}
